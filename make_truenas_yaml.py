"""Build truenas-app.yaml (TrueNAS Apps > Custom App > Install via YAML).

The server script lives in the app's work dataset as /work/ps4_mcp.py and the
YAML pins its SHA-256: the container refuses to start a script whose hash does
not match, so a file dropped into /work (the server's own download tool can
write there) never runs unless the YAML is updated too. (Embedding the script
made the YAML too big for TrueNAS's Save at ~72 KB.)

After editing ps4_mcp.py:
  1. python make_truenas_yaml.py ...   (writes truenas-app.yaml and an LF copy
     of the script to work/ps4_mcp.py)
  2. upload work/ps4_mcp.py to the PS4 as /data/ps4-mcp/ps4_mcp.py (ps4 upload tool),
     then the NAS server's download("/data/ps4-mcp/ps4_mcp.py", "ps4_mcp.py")
     puts it in /work
  3. paste the new YAML (only the hash line changes) into the app's Edit screen.

Usage: PS4_HOST=<ps4 ip> python make_truenas_yaml.py [/mnt/<pool>/<dataset>] [https://public.url] [/mnt/<pool>/<ts-state-dataset>]

With a public URL and a Tailscale state dataset, a tailscale sidecar joins the
tailnet as host "ps4-mcp" (no auth key: approve it via the login link in its
logs) and Funnels https://ps4-mcp.<tailnet>.ts.net (port 443) to the server.
"""

import hashlib
import json
import os
import sys
from pathlib import Path

here = Path(__file__).parent
# read_text already turns CRLF into LF (universal newlines), so the deployed bytes are LF.
deploy = (here / "ps4_mcp.py").read_text(encoding="utf-8").encode("utf-8")
(here / "work").mkdir(exist_ok=True)
(here / "work" / "ps4_mcp.py").write_bytes(deploy)
src_sha = hashlib.sha256(deploy).hexdigest()
hints_deploy = (here / "hints_server.py").read_text(encoding="utf-8").encode("utf-8")
(here / "work" / "hints_server.py").write_bytes(hints_deploy)
hints_sha = hashlib.sha256(hints_deploy).hexdigest()

ps4_host = os.environ.get("PS4_HOST", "192.168.0.50")  # your PS4's IP (set PS4_HOST when generating)
workdir = sys.argv[1] if len(sys.argv) > 1 else "/mnt/CHANGE_ME/ps4-mcp"
public_url = sys.argv[2] if len(sys.argv) > 2 else ""  # https URL from the tunnel; empty = static token only
ts_state = sys.argv[3] if len(sys.argv) > 3 else ""    # dataset for the tailscale sidecar's node state

# Tailscale serve/funnel config; containerboot fills in the cert domain at runtime.
# Compose would interpolate "$", so it is written as "$$" here.
# 443 is the public MCP endpoint (Funnel). 8443 is the phone hints page: tailnet only,
# because it is NOT listed under AllowFunnel and has no login of its own.
serve = {
    "TCP": {"443": {"HTTPS": True}, "8443": {"HTTPS": True}},
    "Web": {
        "${TS_CERT_DOMAIN}:443": {"Handlers": {"/": {"Proxy": "http://ps4-mcp:8765"}}},
        "${TS_CERT_DOMAIN}:8443": {"Handlers": {"/": {"Proxy": "http://ps4-hints:8780"}}},
    },
    "AllowFunnel": {"${TS_CERT_DOMAIN}:443": True},
}
serve_json = json.dumps(serve, separators=(",", ":")).replace("$", "$$")
sidecar = f"""
  tailscale:
    image: tailscale/tailscale:stable
    # No "hostname: ps4-mcp" here: it would shadow the ps4-mcp service name and the
    # proxy below would loop back to this container. TS_HOSTNAME sets the tailnet name.
    restart: unless-stopped
    volumes:
      - "{ts_state}:/var/lib/tailscale"
    environment:
      TS_HOSTNAME: ps4-mcp
      TS_STATE_DIR: /var/lib/tailscale
      TS_USERSPACE: "true"
      TS_SERVE_CONFIG: /tmp/serve.json
      TS_SERVE_JSON: '{serve_json}'
    entrypoint:
      - sh
      - -c
      - printf '%s' "$$TS_SERVE_JSON" > /tmp/serve.json && exec /usr/local/bin/containerboot
""" if (public_url and ts_state) else ""

yaml = f"""# ps4-mcp on TrueNAS. Generated by make_truenas_yaml.py; edit ps4_mcp.py instead.
# Before installing: create the dataset below and change the volume path to it.
services:
  ps4-mcp:
    image: python:3.13-slim
    restart: unless-stopped
    ports:
      - "8765:8765"
    volumes:
      - "{workdir}:/work"
    environment:
      PS4_HOST: "{ps4_host}"
      PS4_FTP_PORT: "2121"
      PS4_PAYLOAD_PORT: "9090"
      PS4_KLOG_PORT: "3232"
      PS4_WORKDIR: /work
      MCP_BIND: 0.0.0.0
      MCP_PORT: "8765"
      PYTHONUNBUFFERED: "1"
      # Public https base URL (tunnel). Set it to turn on OAuth for claude.ai connectors.
      PS4_MCP_PUBLIC_URL: "{public_url}"
      # SHA-256 of /work/ps4_mcp.py; the container will not start any other script.
      PS4_MCP_SHA256: "{src_sha}"
    command:
      - sh
      - -c
      - |
        cp /work/ps4_mcp.py /tmp/ps4_mcp.py &&
        echo "$$PS4_MCP_SHA256  /tmp/ps4_mcp.py" | sha256sum -c - &&
        pip install --no-cache-dir --root-user-action=ignore 'mcp[cli]==2.3.0' &&
        exec python /tmp/ps4_mcp.py --http

  ps4-hints:
    image: python:3.13-slim
    restart: unless-stopped
    volumes:
      - "{workdir}:/work"
    working_dir: /tmp
    environment:
      PS4_HOST: "{ps4_host}"
      PS4_FTP_PORT: "2121"
      PS4_KLOG_PORT: "3232"
      PS4_WORKDIR: /work
      HINTS_DIR: /work/hints
      HINTS_PORT: "8780"
      PYTHONUNBUFFERED: "1"
      PS4_MCP_SHA256: "{src_sha}"
      HINTS_SHA256: "{hints_sha}"
    command:
      - sh
      - -c
      - |
        cp /work/ps4_mcp.py /work/hints_server.py /tmp/ &&
        echo "$$PS4_MCP_SHA256  /tmp/ps4_mcp.py" | sha256sum -c - &&
        echo "$$HINTS_SHA256  /tmp/hints_server.py" | sha256sum -c - &&
        pip install --no-cache-dir --root-user-action=ignore 'mcp[cli]==2.3.0' &&
        exec python /tmp/hints_server.py
{sidecar}"""

out = here / "truenas-app.yaml"
out.write_text(yaml, encoding="utf-8", newline="\n")
print(f"wrote {out} (workdir {workdir}); script sha256 {src_sha} -> work/ps4_mcp.py")
